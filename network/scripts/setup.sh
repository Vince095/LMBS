#!/usr/bin/env bash
# Generates a fresh 4-validator Hyperledger Besu QBFT network for LMBS.
#
# Everything is created under network/generated/ (git-ignored):
#   genesis.json, node1..node4/{key,key.pub}, accounts.json (synthetic keys),
#   permissions_config.toml (node + account allowlists), enodes.txt
#
# Nothing secret is committed: every developer generates their own keys.
# Re-running this script DESTROYS the previous generated network.
#
# Usage:    scripts/setup.sh              (native Besu processes, Linux/macOS)
#           MODE=docker scripts/setup.sh  (then: docker compose up -d)
#
# Requires: besu (>= 24.x, Java 21) on PATH or BESU_BIN set; node >= 18;
#           `npm install` already run in ../blockchain (for ethers).
set -euo pipefail
cd "$(dirname "$0")/.."
BESU="${BESU_BIN:-besu}"
GEN=generated
MODE="${MODE:-native}"   # native = local besu processes; docker = docker-compose.yml

if ! command -v "$BESU" >/dev/null; then
  if [ "$MODE" = "docker" ] && command -v docker >/dev/null; then
    BESU_DOCKER=1   # key/genesis generation runs inside the besu image
  else
    echo "besu not found. Install it (brew install hyperledger/besu/besu) or set BESU_BIN, or use MODE=docker."; exit 1
  fi
fi

if [ -d "$GEN" ]; then
  if [ -f "$GEN/besu.pids" ]; then echo "Network appears to be running; run scripts/stop.sh first."; exit 1; fi
  rm -rf "$GEN"
fi
mkdir -p "$GEN"

echo "1/4  Generating synthetic development accounts"
node scripts/generate-accounts.js

echo "2/4  Building QBFT config with pre-funded dev accounts"
node -e '
  const fs=require("fs");
  const cfg=JSON.parse(fs.readFileSync("config/qbftConfigFile.template.json","utf8"));
  const acc=JSON.parse(fs.readFileSync("generated/accounts.json","utf8"));
  for (const a of acc) cfg.genesis.alloc[a.address.toLowerCase().slice(2)]={balance:"0x3635C9ADC5DEA00000"};
  fs.writeFileSync("generated/qbftConfigFile.json",JSON.stringify(cfg,null,2));
'

echo "3/4  Generating validator keys and genesis (besu operator)"
if [ "${BESU_DOCKER:-0}" = "1" ]; then
  docker run --rm -v "$PWD/$GEN:/gen" hyperledger/besu:25.9.0 operator generate-blockchain-config \
    --config-file=/gen/qbftConfigFile.json --to=/gen/networkFiles --private-key-file-name=key
else
  "$BESU" operator generate-blockchain-config \
    --config-file="$GEN/qbftConfigFile.json" --to="$GEN/networkFiles" --private-key-file-name=key 2>&1 | grep -v "Picked up JAVA_TOOL_OPTIONS" || true
fi
cp "$GEN/networkFiles/genesis.json" "$GEN/genesis.json"

i=1
: > "$GEN/enodes.txt"
for dir in "$GEN"/networkFiles/keys/*/; do
  node_dir="$GEN/node$i"
  mkdir -p "$node_dir/data"
  cp "$dir/key" "$node_dir/key"; cp "$dir/key.pub" "$node_dir/key.pub"
  chmod 600 "$node_dir/key"
  pub=$(sed 's/^0x//' "$node_dir/key.pub")
  if [ "$MODE" = "docker" ]; then host="172.16.239.$((10 + i))"; port=30303; else host=127.0.0.1; port=$((30302 + i)); fi
  echo "enode://$pub@$host:$port" >> "$GEN/enodes.txt"
  echo "$(basename "$dir")" > "$node_dir/validator-address"
  i=$((i + 1))
done

echo "4/4  Writing node and account permissioning allowlists"
node -e '
  const fs=require("fs");
  const en=fs.readFileSync("generated/enodes.txt","utf8").trim().split("\n");
  const acc=JSON.parse(fs.readFileSync("generated/accounts.json","utf8"));
  const q=(xs)=>xs.map(x=>JSON.stringify(x)).join(",\n  ");
  fs.writeFileSync("generated/permissions_config.toml",
    "# Generated by setup.sh. Only these nodes may peer and only these accounts may transact.\n"+
    "nodes-allowlist=[\n  "+q(en)+"\n]\n\naccounts-allowlist=[\n  "+q(acc.map(a=>a.address))+"\n]\n");
'
echo
echo "Network generated in network/generated. Validators:"
for n in 1 2 3 4; do echo "  node$n  $(cat $GEN/node$n/validator-address)"; done
echo "$MODE" > "$GEN/mode"
if [ "$MODE" = "docker" ]; then echo "Next: docker compose up -d   (from the network folder)"; else echo "Next: network/scripts/start.sh"; fi
